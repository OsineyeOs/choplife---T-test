export function getTodayDayKey(): DayOfWeek {
  const dayIndex = new Date().getDay(); // 0 is Sunday, 1 is Monday, etc.
  const found = DAYS_OF_WEEK.find((d) => d.dayIndex === dayIndex);
  return found ? found.key : 'monday';
}
